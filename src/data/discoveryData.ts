export interface Creator {
  id: string
  name: string
  handle: string
  avatar: string
  bio: string
  role: string
  location: string
  followersCount: number
  curatedCount: number
  featured?: boolean
}

export interface VisualItem {
  id: string
  title: string
  subtitle?: string
  creator: Creator
  image: string
  aspectRatio: string // Tailwind aspect class or CSS ratio
  category: 'Architecture' | 'Interiors' | 'Objects' | 'Nocturne' | 'Spaces' | 'Tactile' | 'Typography'
  moods: string[]
  dominantColor: string // Hex code (e.g. #C4622D)
  palette: string[] // Array of 4-5 hex colors
  location: string
  year: string
  savesCount: number
  likesCount: number
  description: string
  tags: string[]
  dimensions?: string
  source?: string
  dateAdded?: string
}

export interface Moodboard {
  id: string
  title: string
  slug: string
  description: string
  itemIds: string[]
  coverImage?: string
  curator: string
  isPrivate?: boolean
  createdAt: string
  tags: string[]
}

