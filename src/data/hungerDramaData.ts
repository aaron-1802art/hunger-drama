// Helper function to build prefilled WhatsApp ordering link for a single dish
export function createWhatsAppOrderUrl(item: MenuItem, quantity: number = 1): string {
  const message = `Hello Hunger Drama! 🍟\n\nI would like to order:\n• ${item.name} (${BRAND_CONFIG.currencySymbol}${item.price} x ${quantity}) = ${BRAND_CONFIG.currencySymbol}${item.price * quantity}\n\nPlease confirm availability and delivery time!`
  return `https://wa.me/${BRAND_CONFIG.whatsappNumber}?text=${encodeURIComponent(message)}`
}

export function createWhatsAppGeneralMessageUrl(text?: string): string {
  const message = text || `Hello Hunger Drama! 🍟 I would like to place an order from your menu.`
  return `https://wa.me/${BRAND_CONFIG.whatsappNumber}?text=${encodeURIComponent(message)}`
}

export function createCartWhatsAppUrl(
  items: { item: MenuItem; quantity: number }[],
  note?: string
): string {
  if (items.length === 0) return createWhatsAppGeneralMessageUrl()

  const subtotal = items.reduce((sum, i) => sum + i.item.price * i.quantity, 0)
  const lines = items.map(
    (i) => `• ${i.item.name} (x${i.quantity}) - ${BRAND_CONFIG.currencySymbol}${i.item.price * i.quantity}`
  )

  let message = `Hello Hunger Drama! 🍟\n\nI would like to place an order:\n\n${lines.join('\n')}\n\nTotal Order: ${BRAND_CONFIG.currencySymbol}${subtotal}`

  if (note && note.trim()) {
    message += `\n\n*Special Instructions:* ${note.trim()}`
  }

  message += `\n\n*Delivery Details:*\nName:\nDelivery Address (Vikaspuri & nearby):\nPhone:\n\nPlease confirm availability and delivery time!`
  return `https://wa.me/${BRAND_CONFIG.whatsappNumber}?text=${encodeURIComponent(message)}`
}
